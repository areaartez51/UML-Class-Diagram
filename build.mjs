// Zero-dependency bundler: turns the vendored renderer plus the plugin source
// into a single CommonJS main.js that Obsidian can load.
//
// Why not esbuild/rollup: the plugin must build without network and without a
// node_modules tree. The renderer modules are ours, use only relative named
// imports, and never touch Node APIs, so inlining them is safe and deterministic.
//
// OBSIDIAN DIFFERENCE: the standalone HTML owns the whole page, so its CSS may use
// bare selectors like `button` or `.title`. Inside Obsidian that would restyle the
// application itself, so every selector is prefixed with the diagram container here.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSpecText, serializeSpec } from './src/specfile.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const VENDOR = join(HERE, 'vendor');
const SCOPE = '.uml-diagram';

// Topological order: a module may only reference the ones above it.
// `client` is not bundled as a module: its code is inlined below, and the plugin
// never renders a standalone document, so the string copy would only add weight.
const ORDER = [
  ['model', 'model'],
  ['layout', 'layout'],
  ['routing', 'routing'],
  ['svg', 'svg'],
  ['theme', 'theme'],
  ['html', 'html'],
  ['render', 'render'],
  ['csharp', 'extract/csharp'],
];

/** The copy in vendor/ must match what the skill repository shipped. */
function verifyVendor() {
  const expected = JSON.parse(readFileSync(join(VENDOR, 'HASHES.json'), 'utf8'));
  for (const [file, hash] of Object.entries(expected)) {
    const actual = createHash('sha256').update(readFileSync(join(VENDOR, file))).digest('hex');
    if (actual !== hash) {
      throw new Error(`vendor/${file} не совпадает с HASHES.json — запустите: node sync-vendor.mjs`);
    }
  }
  return Object.keys(expected).length;
}

function read(path) {
  return readFileSync(join(VENDOR, `${path}.mjs`), 'utf8');
}

function transform(name, source) {
  let code = source;

  // `import { a, b } from './x.mjs'` → registry lookup. Multiline imports included.
  code = code.replace(
    /import\s*\{([\s\S]*?)\}\s*from\s*'\.\/([\w-]+)\.mjs';/g,
    (_match, names, dependency) => {
      const list = names
        .split(',')
        .map((item) => item.trim())
        .filter(Boolean)
        .join(', ');
      return `const { ${list} } = __m.${dependency};`;
    },
  );

  const leftover = code.match(/^\s*import\s.+$/m);
  if (leftover) throw new Error(`${name}.mjs: неразрешённый импорт — ${leftover[0].trim()}`);

  const exported = [...code.matchAll(/^export\s+(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)]
    .map((match) => match[1]);

  code = code.replace(/^export\s+/gm, '');
  return { code, exported };
}

/** Prefix every CSS selector with the diagram container, keeping at-rules intact. */
function scopeCss(css, scope) {
  let out = '';
  let index = 0;
  while (index < css.length) {
    const open = css.indexOf('{', index);
    if (open === -1) {
      out += css.slice(index);
      break;
    }
    let depth = 0;
    let close = -1;
    for (let i = open; i < css.length; i += 1) {
      if (css[i] === '{') depth += 1;
      else if (css[i] === '}') {
        depth -= 1;
        if (depth === 0) {
          close = i;
          break;
        }
      }
    }
    if (close === -1) {
      out += css.slice(index);
      break;
    }

    const headRaw = css.slice(index, open);
    const leading = headRaw.match(/^\s*/)[0];
    const selectorText = headRaw.trim();
    const body = css.slice(open + 1, close);

    if (selectorText.startsWith('@')) {
      const nestable = /^@(media|supports|container|layer)\b/.test(selectorText);
      out += `${leading}${selectorText}{${nestable ? scopeCss(body, scope) : body}}`;
    } else {
      const selectors = selectorText
        .split(',')
        .map((part) => part.trim())
        .filter(Boolean)
        .map((selector) =>
          selector.startsWith(scope) || selector.startsWith('.uml-page') ? selector : `${scope} ${selector}`,
        )
        .join(', ');
      out += `${leading}${selectors}{${body}}`;
    }
    index = close + 1;
  }
  return out;
}

function unscopedSelectors(css) {
  const selectors = [...css.matchAll(/(?:^|\})\s*([^{}@]+)\{/g)].map((match) => match[1].trim()).filter(Boolean);
  return selectors.filter(
    (selector) =>
      !selector.split(',').every((part) => {
        const item = part.trim();
        return item.startsWith(SCOPE) || item.startsWith('.uml-page') || item.startsWith('@');
      }),
  );
}

const vendorFiles = verifyVendor();

const chunks = [
  '// Generated by build.mjs — do not edit by hand.',
  "'use strict';",
  'const __m = {};',
  // html.mjs imports CLIENT for the standalone page; inside a host there is no page.
  "__m.client = { CLIENT: '' };",
];

for (const [id, path] of ORDER) {
  const { code, exported } = transform(id, read(path));
  chunks.push(`__m.${id} = (function () {\n${code}\nreturn { ${exported.join(', ')} };\n})();`);
}

// Spec file format: checked here, so a broken reader cannot ship silently.
const probe = { title: 'probe', classes: [{ name: 'A' }], relations: [] };
if (JSON.stringify(parseSpecText(serializeSpec(probe, 'probe'))) !== JSON.stringify(probe)) {
  throw new Error('specfile: формат не переживает запись и чтение');
}
const specfileSource = readFileSync(join(HERE, 'src', 'specfile.mjs'), 'utf8').replace(/^export\s+/gm, '');
chunks.push(`__m.specfile = (function () {\n${specfileSource}\nreturn { serializeSpec, parseSpecText };\n})();`);

// Scoped stylesheet: the same CSS, but nothing leaks into the host application.
const themeSource = read('theme');
const styleMatch = themeSource.match(/export const STYLE = `([\s\S]*?)`;\s*$/);
if (!styleMatch) throw new Error('theme.mjs: не найден литерал STYLE');
const scopedStyle = scopeCss(styleMatch[1], SCOPE);
const leaked = unscopedSelectors(scopedStyle);
if (leaked.length) throw new Error(`стили не изолированы: ${leaked.slice(0, 5).join(' | ')}`);
chunks.push(`const __SCOPED_STYLE = ${JSON.stringify(scopedStyle)};`);

// The client script is stored as a template literal for the standalone HTML.
// In the bundle it is emitted as real code: an IIFE that defines window.__umlClassMount.
const clientSource = read('client');
const clientMatch = clientSource.match(/export const CLIENT = `([\s\S]*?)`;\s*$/);
if (!clientMatch) throw new Error('client.mjs: не найден литерал CLIENT');
chunks.push(`// client runtime, inlined from client.mjs\n${clientMatch[1]}`);

chunks.push(readFileSync(join(HERE, 'src', 'plugin.js'), 'utf8'));

const bundle = `${chunks.join('\n\n')}\n`;
writeFileSync(join(HERE, 'main.js'), bundle, 'utf8');

console.log(`main.js: ${(bundle.length / 1024).toFixed(1)} КБ, ${bundle.split('\n').length} строк`);
console.log(`стили: ${(scopedStyle.length / 1024).toFixed(1)} КБ, все селекторы под ${SCOPE}`);
console.log(`vendor: ${vendorFiles} файлов, хеши сходятся`);
